// Nomes de categoria vêm do banco (cadastrados em português pelo admin) e não
// passam pelo dicionário acima. Tradução manual pros nomes conhecidos hoje —
// categoria nova cadastrada depois aparece em português até alguém adicionar
// aqui, o que é melhor do que travar a página esperando um cadastro trilíngue.
const CATEGORY_TRANSLATIONS: Record<string, { es: string; en: string }> = {
  'PERFUMARIA': { es: 'PERFUMERÍA', en: 'FRAGRANCE' },
  'PARA CABELOS': { es: 'PARA EL CABELLO', en: 'HAIR CARE' },
  'FARMACIA': { es: 'FARMACIA', en: 'PHARMACY' },
  'PERFORMANCE': { es: 'PERFORMANCE', en: 'PERFORMANCE' },
  'PARA O CORPO': { es: 'PARA EL CUERPO', en: 'BODY CARE' },
  'CORPO': { es: 'CUERPO', en: 'BODY' },
};

export function translateCategoryName(name: string, lang: string): string {
  if (!name || lang === 'pt') return name;
  const entry = CATEGORY_TRANSLATIONS[name.trim().toUpperCase()];
  if (!entry) return name;
  return lang === 'en' ? entry.en : entry.es;
}

// Traduz o status de estoque vindo do servidor (stockStatus/stockQty, sem
// texto pronto - o backend so manda o status maquina, quem escreve o texto
// certo pro idioma e o cliente). Ver publicStock() em src/server/store.ts.
export function translateStockStatus(t: (key: string, opts?: any) => string, status: string, qty?: number): string {
  if (status === 'available') return t('product.disponivel');
  if (status === 'out') return t('product.esgotado');
  return t('product.ultimasUnidades', { qty });
}

